/// ISO 3166-1 country list used by onboarding and Settings to infer the
/// user's currency from their country of residence. Flag glyphs are computed
/// from the ISO alpha-2 code (regional indicator symbols) rather than stored,
/// so adding a country only needs a name + currency code.
class Country {
  const Country({required this.code, required this.name, required this.currencyCode});

  final String code;
  final String name;
  final String currencyCode;

  String get flag => String.fromCharCodes(
        code.toUpperCase().codeUnits.map((c) => 0x1F1E6 + (c - 0x41)),
      );
}

String? currencyCodeForCountry(String countryCode) {
  for (final country in countries) {
    if (country.code == countryCode) return country.currencyCode;
  }
  return null;
}

String? countryNameForCode(String countryCode) {
  for (final country in countries) {
    if (country.code == countryCode) return country.name;
  }
  return null;
}

